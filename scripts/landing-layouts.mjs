// Exports the intake diagrams (src/shared/carLayouts.ts) for the landing page, so the page shows
// exactly the app's diagram and numbering. Run after changing the layouts: node scripts/landing-layouts.mjs
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { BODY_TYPES, QUICK_NOTES, carLayout } from '../src/shared/carLayouts.ts';

const layouts = Object.fromEntries(BODY_TYPES.map(({ code }) => [code, carLayout(code)]));
const data = { bodyTypes: BODY_TYPES, quickNotes: QUICK_NOTES, layouts };
const target = resolve('public/landing22/car-layouts.js');
await writeFile(target, `// Generated by scripts/landing-layouts.mjs from src/shared/carLayouts.ts. Do not edit.\nwindow.DF_LAYOUTS = ${JSON.stringify(data)};\n`);
console.log('written', target);
